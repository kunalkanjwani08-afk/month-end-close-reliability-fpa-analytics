"""Generate dashboard/DASHBOARD_QA_REPORT.md from the QA artefacts.

Inputs (all produced by earlier steps, nothing is re-run here):
  dashboard/qa_results.json         <- tests/dashboard_browser_qa.py
  dashboard/negative_controls.json  <- tests/dashboard_negative_controls.py
  dashboard/payload_stats.json      <- src/dashboard_builder.py
  the built HTML (hash / size are computed here)
Counts are derived from the JSON; nothing is hard-coded except prose.
"""
import hashlib, json, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build" / "dashboard_qa"
HTML = ROOT / "dashboard" / "fpa_financial_analytics_dashboard.html"

qa = json.loads((OUT / "qa_results.json").read_text())
neg = json.loads((OUT / "negative_controls.json").read_text())
pst = json.loads((OUT / "payload_stats.json").read_text())

res = qa["results"]
skips = qa.get("skips", [])
cnt = collections.Counter(r["status"] for r in res)
n_pass, n_fail = cnt.get("PASS", 0), cnt.get("FAIL", 0)
n_skip = len(skips)
sha = hashlib.sha256(HTML.read_bytes()).hexdigest()
size = HTML.stat().st_size

def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")

L = []
A = L.append
A("# Dashboard dashboard - QA report (corrections round + interactive redesign)\n")
A(f"File: `dashboard/fpa_financial_analytics_dashboard.html` - {size:,} bytes ({size/1e6:.2f} MB), sha256 `{sha}`. Standalone, no network resources.\n")
A("Build: `src/dashboard_builder.py` + `dashboard_template.html`, `dashboard_style.css`, `dashboard_core.js`, `dashboard_views.js`. "
  "Tests: `tests/dashboard_browser_qa.py` (real Chromium via Playwright against the built file) and `tests/dashboard_negative_controls.py`. "
  "This report: `src/dashboard_qa_report.py`.\n")
A(f"## Result\n\n**{n_pass} PASS / {n_fail} FAIL / {n_skip} SKIP** of {len(res)+n_skip} browser checks "
  "(the original 132 tests are retained and still pass after two wording updates; the rest are new). "
  f"Negative controls: **{sum(1 for n in neg if n['defect_detected_by_check'])}/{len(neg)}** re-introduced defects were detected by the suite. "
  "In-page baseline checks 459/459; in-page selection checks 11/11 (see limitations - these are not independent).\n")
A("Reporting rule: PASS, FAIL and SKIP are counted separately. A SKIP is a check that could not be performed, not a pass.\n")

A("## What was corrected (ChatGPT review items, each analysed first)\n")
A("| # | Finding | Verdict | Action |\n|---|---|---|---|")
for row in [
 ("1", "Zero-bar cross-filter creates an empty US01 + AE01 intersection", "Correct - reproduced exactly", "Selectability guard `xfOK`/`elig` (same-dimension chart selection ignored, other dimensions respected); disabled bars with `aria-disabled`, a reason notice on click or keyboard; invalid chart selection auto-cleared when a slicer change empties it"),
 ("2", "Header `#scope` is static", "Correct", "`scopeHtml()` rebuilds the subtitle from the live state (scale, duplicate, sign, population, filters) and states that other pages use other populations"),
 ("3", "Journal-status cube ignores GL, cost-centre and scenarios", "Correct", "Preferred option implemented: the 77,990 non-Posted lines are embedded at line level; status tables respect every filter and the chosen scale/duplicate/sign settings; Gross Profit sensitivity rows use baseline scenario settings (declared)"),
 ("4", "'Reconciled 459/459' over-claims", "Correct", "Badge now 'Baseline checks: N/N' with an explanatory title; separate 'Selection checks' badge; Quality tab states the difference"),
 ("5", "Derived metrics not independently tested under filters", "Correct", "pandas reference engine built from the cleaned CSV; 14 filter/scenario states x 11 metric families compared (154 comparisons)"),
 ("6", "Three light chart colours below 3:1", "Correct (3:1 is a fair graphical target)", "Replaced; dash patterns, markers and bar textures added; palette run through the dataviz validator in both themes"),
 ("7", "Variance population label unclear", "Correct", "Renamed 'Variance-comparison population', per-option counts shown, collapsible note stating which views it affects"),
 ("8", "Verify all interactions", "Correct", "Extended suite (tabs, charts, toggle, chips, undo/reset, themes, search/sort/pagination/CSV, empty/zero/negative, responsive, print restore, console)"),
 ("9", "Data integrity / publication", "Process rule - followed", "Hashes rechecked before and after; nothing committed, pushed or published"),
 ("10", "Rebuild through generator, report PASS/FAIL/SKIP", "Process rule - followed", "All changes made in generator, template, CSS, JS and tests; report generated by script"),
]:
    A("| " + " | ".join(esc(x) for x in row) + " |")
A("\nNote: the request header mentioned Excel workbook / SQL / Excel. The content is the dashboard dashboard review only; it contains no SQL or Excel finding, so the Excel workbook workbook was deliberately not changed (hash verified unchanged).\n")

A("## Interactive redesign round (user request after the corrections round)\n")
for t in [
 "**Logo** (original NovaBridge mark, inline SVG) in the upper-left corner, with an accessible name.",
 "**Header reduced to one line.** The long 'Synthetic dataset ...' and 'Not every page uses this population ...' lines were removed from the visible header. The dynamic basis is kept (collapsed 'Baseline basis' details); when any scenario is active a visible SCENARIO ACTIVE flag and the changed settings appear inline, so the header can never mislabel the figures. The synthetic-data disclosure stays in the footer and the Quality & Methodology tab.",
 "**Every KPI card has a trend chart** (monthly revenue, cost base, result proxy, revenue and cost-base net variance) with hover tooltips, click-to-filter-month and keyboard support, plus a YoY badge (same months of the prior year, n/a when no aligned months) and a drill-through button to the matching Trends metric or Budget & Variance tab.",
 "**New charts, each added for a specific analytical reason:** Result proxy bridge (Revenue to Result, step click filters the section); Proxy margin by entity (ratio not visible in the existing revenue and result charts); Cumulative net variance vs budget (shows whether gaps build up); Proxy margin trend with trailing 3-month margin. Nothing decorative was added.",
 "**Real defect found by the new regression test and fixed:** the print routine opened the header basis and the open state leaked into the live page afterwards. State is now restored after print (negative control M6 re-introduces it and is detected).",
]:
    A("- " + t)
A("")
A("## Payload\n")
A(f"- Posted-eligible lines embedded: {pst['rows']:,}. Non-Posted lines embedded for the journal-status diagnostic: {pst['nonposted_status_rows']:,}. "
  f"Restored (scale-adjusted) rows: {pst['restored_rows']:,} Posted, {pst['nonposted_restored_rows']:,} non-Posted.\n"
  "- Size cost of the line-level status rebuild: about +2.2 MB. The file embeds 136,330 journal lines and must stay private/local until provenance, licence and sensitivity are reviewed.\n")

A("## Performance (headless Chromium, local file; one run, not a benchmark)\n")
A(f"File {size/1e6:.2f} MB; DOMContentLoaded {qa['dcl_ms']:.0f} ms; load {qa['load_ms']:.0f} ms; app boot incl. baseline checks {qa['boot_ms']:.0f} ms. Filter-change timings are in the Performance row below.\n")

A("## Negative controls (the suite must fail when the defect is re-introduced)\n")
A("| Mutant | Detected | Evidence |\n|---|---|---|")
for n in neg:
    A(f"| {esc(n['mutant'])} | {'YES' if n['defect_detected_by_check'] else 'NO'} | {esc(n['detail'])} |")
A("")

A("## Results by area\n")
byarea = collections.OrderedDict()
for r in res:
    byarea.setdefault(r["area"], []).append(r)
for area, rows in byarea.items():
    p = sum(1 for r in rows if r["status"] == "PASS")
    A(f"### {area} ({p}/{len(rows)} pass)\n")
    A("| Test | Result | Detail |\n|---|---|---|")
    for r in rows:
        d = str(r.get("detail", ""))
        A(f"| {esc(r['test'])} | {r['status']} | {esc(d[:400])} |")
    A("")

A("## SKIP (not performed)\n")
A("| Area | Check | Reason |\n|---|---|---|")
for s in skips:
    A("| " + " | ".join(esc(x) for x in s) + " |")
A("")

A("## Limitations and scope statements (stated, not hidden)\n")
for t in [
 "**Selection checks are not independent.** The in-page 'Selection checks 11/11' compare two implementations inside the same page; independence comes only from the pandas reference tests in this suite, which cover the listed filter/scenario states, not every possible combination.",
 "**Baseline checks 459/459** compare default-filter values to embedded SQL analysis reference tables; they say nothing about arbitrary filtered views.",
 "**Independent verification at non-default states** was done for lines, revenue, cost, variance, forecast WAPE/bias/populations, prior-year, GP treatments and row sets, persistence, concentration, status totals and insight counts in 14 states. Dynamic insight driver names were checked for persistent cells only.",
 "**Variance-comparison population** changes variance, forecast and prior-year comparisons; it does not filter lines. Status lines labelled Pending, Parked, Rejected or blank exist only in the status diagnostic.",
 "**Cross-browser:** Chromium only. Firefox and Safari were not tested.",
 "**Screen reader:** not tested (no assistive technology available). ARIA attributes, roles, names and live regions are asserted programmatically; keyboard operation was tested.",
 "**Print:** tested via print-media emulation, before/after-print state restoration and a generated PDF preview; no physical printer. Print outputs the visible tab; the Detail table prints only the visible page, and 'Export all filtered lines (CSV)' provides every matching line.",
 "**SQL analysis insight text** (fixed findings) does not change with filters; it is labelled as portfolio-level.",
 "**Data provenance** of the synthetic extract is unverified (scale, sign convention R9, FX and duplicate questions remain open and are disclosed in the dashboard).",
 "**Contrast:** light-theme marks >= 3.12:1, dark-theme marks >= 3.52:1 against the card surface; text >= 4.5:1 in both themes. Patterns and markers carry identity in addition to colour.",
]:
    A("- " + t)
A("")
A("## Data integrity\n")
A("Cleaned CSV, raw CSV, SQL analysis DuckDB and the Excel workbook workbook were hash-checked before and after the work and are unchanged. No data was cleaned, deduplicated, imputed, re-scaled or re-signed. Nothing was committed, pushed or published.\n")

(OUT / "DASHBOARD_QA_REPORT.md").write_text("\n".join(L), encoding="utf-8")
print("report written", n_pass, n_fail, n_skip, sha, size)
